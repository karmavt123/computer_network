#!/usr/bin/env python3
"""gen_validation_doc.py - write Docs/05_Validation.md with the current test counts and emulation results."""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def tests(mod):
    r = subprocess.run([sys.executable, "-m", "unittest", "-v", mod], cwd=ROOT, capture_output=True, text=True)
    names = re.findall(r"^(test_\w+) \((\S+)\)(?:\n.*?)? \.\.\. ok$", r.stderr, re.M)
    n = int(re.search(r"Ran (\d+) tests?", r.stderr).group(1))
    return n, "OK" in r.stderr.splitlines()[-1], [x[0] for x in names]


def main():
    tm, tc = tests("Tools.test_model"), tests("Tools.test_configs")
    ta, te = tests("Automation.tests.test_auto_provision"), tests("Automation.tests.test_collect_evidence")
    j = json.loads((ROOT / "Tools/frr_emulation/results/summary.json").read_text())
    sc = j["scenarios"]
    single = [s for s in sc if not s["title"].startswith("DOUBLE")]
    L = ["# Validation", "",
         "> Generated by `Tools/gen_validation_doc.py` from the current test runs and "
         "`Tools/frr_emulation/results/summary.json`.", "",
         "The project is checked at four levels. Each level proves something the previous one cannot, and none of the "
         "first three replaces the fourth.", "",
         "| Level | Tool | Needs | Proves | Cannot prove |", "|---|---|---|---|---|",
         f"| 1. Data model | `Tools/test_model.py` ({tm[0]} tests) | Python | The plan is consistent: no overlapping subnets, "
         "capacity >= demand, unique addresses, every referenced ACL / policy exists, STP root = HSRP owner | That the "
         "rendered text says what the model means |",
         f"| 2. Rendered configs | `Tools/test_configs.py` ({tc[0]} tests) | Python | Both ends of every BGP session, OSPF "
         "adjacency, HSRP group, IPsec tunnel and trunk agree - read from the `.cfg` text only | That the protocols "
         "converge to the intended paths |",
         f"| 3. Routing emulation | `Tools/frr_emulation/emulate.py` ({len(sc)} scenarios) | Linux, root, FRR | The routing "
         "logic converges and fails over: real OSPF/BGP daemons run the translated IPv4 routing sections | IOS syntax, "
         "IPsec, L2, IPv6, ACL/ZBF/QoS behaviour |",
         "| 4. Lab | `Lab/Test_Plan.md`, `Lab/collect_evidence.py` | EVE-NG + IOSv/IOSvL2 | Everything, on the graded "
         "platform | - |", "",
         f"Automation code: {ta[0] + te[0]} unit tests with a mocked SSH connection "
         "(`Automation/tests/`).", "",
         "```bash",
         "python3 -m unittest Tools.test_model Tools.test_configs \\",
         "        Automation.tests.test_auto_provision Automation.tests.test_collect_evidence",
         "sudo python3 Tools/frr_emulation/emulate.py",
         "```", "",
         "## 1. Status", "",
         "| Level | Result |", "|---|---|",
         f"| 1 | {tm[0]} tests, {'all pass' if tm[1] else '**FAILING**'} |",
         f"| 2 | {tc[0]} tests, {'all pass' if tc[1] else '**FAILING**'} |",
         f"| Automation | {ta[0] + te[0]} tests, {'all pass' if ta[1] and te[1] else '**FAILING**'} |",
         f"| 3 | baseline: {j['baseline']['bgp_up']}/{j['baseline']['bgp_total']} BGP sessions established, all "
         f"{len(j['baseline']['paths'])} test flows reachable; {sum(s['passed'] for s in single)}/{len(single)} "
         "single-failure scenarios recover; the deliberate double failure fails as predicted |",
         "| 4 | **not done here** - to be executed by the team; nothing in this repository is an IOSv output |", "",
         "## 2. What the rendered-config tests check", ""]
    for n in tc[2]:
        L.append(f"* `{n}`")
    L += ["", "## 3. Emulation results", "",
          "Link model: every link passes through a bridge, as in EVE-NG - a failed interface or dead router leaves the "
          "far end up/up, so the neighbours detect the failure with protocol timers. Ping every 0.2 s; *worst outage* = "
          "longest run of lost echoes among the eight test flows.", "",
          "| ID | Failure | Result | Worst outage | Flows down at the end | HSRP moves |", "|---|---|---|---|---|---|"]
    for s in sc:
        worst = max(v["longest_outage_s"] for v in s["flows"].values())
        broken = [k for k, v in s["flows"].items() if not v["final_ok"]]
        moves = len([e for e in s["hsrp_events"] if 0 <= e["t_after_failure"] <= 30])
        L.append(f"| {s['id']} | {s['title']} | {'pass' if s['passed'] else '**fail (expected)**' if s in sc and s not in single else '**FAIL**'} | "
                 f"{worst} s | {len(broken)} | {moves} |")
    L += ["", "Full detail (per-flow loss, paths after each failure, router outputs): "
          "`Tools/frr_emulation/results/EMULATION_RESULTS.md`.", "",
          "### How to read the outages", "",
          "* **About 9 s** wherever the *far end* of a tunnel has to notice the failure: nothing but the BGP hold timer "
          "(3 s keepalive / 9 s hold) tells a hub that a spoke's uplink died, or a spoke that the hub's did.",
          "* **About 4 s** when traffic was transiting a router that died silently: OSPF dead interval.",
          "* **Under 2 s** for a gateway failure: HSRP hold time 1.5 s.",
          "* **About 1 s** when the failing interface belongs to the router that has to react: it sees its own link "
          "go down and the track object follows at the next 1 s poll. IOS is slower here than FRR (BGP next-hop "
          "trigger delay of 5 s) - expect a few seconds in the lab.", "",
          "### What the emulation found", "",
          "| Finding | Seen as | Fix | Guarded by |", "|---|---|---|---|",
          "| Routing loop between a core switch and an HQ edge after a branch-uplink failure | traceroute "
          "`CORE -> EDGE-RTR01 -> CORE -> ...`, \"Time to live exceeded\" (still reproducible as S9) | edge-to-edge routed "
          "link | `test_edge_to_edge_link` |",
          "| Dead HQ edge kept as best path by its peer (next hop resolved through the Null0 summary) | S3 never "
          "recovered within the measurement window | `timers 3 9` on the edge-to-edge iBGP session | "
          "`test_every_ibgp_session_has_fast_timers` |",
          "| 40 s OSPF dead interval when the neighbour dies without a link-down event | found by reasoning, "
          "reproduced by the bridged link model | hello 1 s / dead 4 s | "
          "`test_non_passive_interfaces_have_exactly_one_matching_neighbor` |",
          "| Standby gateway waiting for its own preempt delay; 15 s track polling | found by reasoning | delay only on "
          "the designed owner; `track timer ip route 1` | `test_hsrp_standby_preempts_without_delay`, "
          "`test_priorities_differ_and_tracking_can_flip_the_role` |", "",
          "## 4. Residual risks (known, accepted)", "",
          "* **Double failure** of the HQ edge-to-edge link *and* a branch tunnel on the primary ISP re-creates the loop "
          "(S9). Mitigations for production: a second edge-to-edge link in a port-channel, or iBGP on the core switches.",
          "* **One access switch per branch** in the lab: its failure isolates that branch's hosts.",
          "* **Detection bound of 9 s** on tunnels; BFD is the roadmap item.",
          "* **A dead ISP router that keeps its customer link up** is detected by BGP hold (9 s), not by link state.", "",
          "## 5. What only the lab can prove", "",
          "1. Every line is accepted by the IOSv / IOSvL2 images in use (candidates for rejection: `storm-control`, "
          "the zone-based firewall block, `track timer ip route`, `ip verify unicast`, some QoS lines). Record what you "
          "remove.",
          "2. IPsec comes up (`QM_IDLE`) and BGP runs through it.",
          "3. Layer 2: LACP, RSTP roles, root guard, DHCP snooping, DAI, port security.",
          "4. HSRP timing with real hellos; DHCP relay end to end; NTP; DNS.",
          "5. ACL matrix, NAT, firewall zones, QoS counters.",
          "6. IPv6: OSPFv3 adjacencies, MP-BGP sessions, the HSRP IPv6 groups.",
          "7. The automation against real SSH servers.", "",
          "`Lab/Test_Plan.md` lists the command and the pass criterion for each, and `Lab/collect_evidence.py` "
          "stores the outputs for the report."]
    (ROOT / "Docs/05_Validation.md").write_text("\n".join(L) + "\n")
    print("validation doc written:", tm[0], tc[0], ta[0] + te[0], "tests;", len(sc), "scenarios")


if __name__ == "__main__":
    main()
