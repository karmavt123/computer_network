def facts():
    (OUT / "generated").mkdir(parents=True, exist_ok=True)

    def run_tests(mod):
        r = subprocess.run([sys.executable, "-m", "unittest", mod], cwd=ROOT, capture_output=True, text=True)
        mt = re.search(r"Ran (\d+) tests?", r.stderr)
        return int(mt.group(1)) if mt and "OK" in r.stderr else 0
    iot_dn = next(r[4] for r in gd.capacity_rows() if r[0] == m.SITES["DN"]["code"])   # same rule as the IP plan
    F = {
        "NumDevices": len(m.DEVICES), "NumConfigs": len(CFG_TEXT), "NumLinks": len(m.LINKS),
        "NumTunnels": len(m.TUNNELS), "NumHosts": len(m.HOSTS),
        "NumBgpSessions": len(re.findall(r"& [ie]BGP &", (OUT / "tables/bgp.tex").read_text())),
        "NumHsrpGroups": len({(m.DEVICES[dev]["site"], g) for dev, c in CFG.items()
                              for d in c.interfaces.values() for g, h in d["hsrp"].items() if h["vip"]}),
        "AsTvi": m.AS_TVI, "AsIspA": m.AS_ISP_A, "AsIspB": m.AS_ISP_B,
        "WanRateMbps": m.WAN_RATE_BPS // 1_000_000,
        "IotCapacityDanang": f"{iot_dn:,}",
        "TestsModel": run_tests("Tools.test_model"), "TestsConfigs": run_tests("Tools.test_configs"),
        "TestsAutomation": run_tests("Automation.tests.test_auto_provision") + run_tests("Automation.tests.test_collect_evidence"),
        "NumEvidence": (ROOT / "Lab/evidence_plan.yaml").read_text().count("\n- id:"),
        "NumSnippets": len(list((OUT / "snippets").glob("*"))),
    }
    summ = HERE / "frr_emulation" / "results" / "summary.json"
    if summ.exists():
        j = json.loads(summ.read_text())
        F["EmuScenarios"] = len(j["scenarios"])
        F["EmuPassed"] = sum(r["passed"] for r in j["scenarios"])
        F["EmuBgpSessions"] = j["baseline"]["bgp_up"]
    out = [HEADER]
    for k, v in F.items():
        out.append(f"\\newcommand{{\\Fact{k}}}{{{v}}}")
    (OUT / "generated/facts.tex").write_text("\n".join(out) + "\n")
    return F


def main():
    tables()
    n = snippets()
    try:
        nf = figures()
    except Exception as e:                                   # playwright missing: keep the PNGs
        nf = 0
        print("figures: skipped (", type(e).__name__, e, ") - the report falls back to Design/img/*.png")
    f = facts()
    print(f"latex inputs generated: {len(list((OUT / 'tables').glob('*.tex')))} tables, {n} snippets, {nf} figures, {len(f)} facts")


if __name__ == "__main__":
    main()
