def tex(s) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s.replace("->", r"$\rightarrow$")


def mono(s) -> str:
    return r"\texttt{" + tex(s) + "}"


def table(name, colspec, head, rows, caption, label, long=False, font=r"\footnotesize"):
    """Write tables/<name>.tex.  `long` -> longtable (breaks across pages), else a floating table."""
    hd = " & ".join(r"\textbf{" + tex(h) + "}" for h in head) + r" \\"
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    if long:
        t = (f"{font}\n\\begin{{longtable}}{{{colspec}}}\n\\caption{{{caption}}}\\label{{{label}}}\\\\\n\\toprule\n{hd}\n"
             f"\\midrule\n\\endfirsthead\n\\toprule\n{hd}\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n{body}\n"
             f"\\end{{longtable}}\n\\normalsize\n")
    else:
        t = (f"\\begin{{table}}[htbp]\n\\centering{font}\n\\caption{{{caption}}}\\label{{{label}}}\n"
             f"\\begin{{tabularx}}{{\\textwidth}}{{{colspec}}}\n\\toprule\n{hd}\n\\midrule\n{body}\n\\bottomrule\n"
             f"\\end{{tabularx}}\n\\end{{table}}\n")
    (OUT / "tables" / f"{name}.tex").write_text(HEADER + t)


