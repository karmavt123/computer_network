def cfg_block(dev, start_re, end_re=None, include_end=False, max_lines=60):
    """Lines of dev's config from the first line matching start_re up to (not incl.) the next '!' or end_re."""
    lines = CFG_TEXT[dev].splitlines()
    i = next(k for k, ln in enumerate(lines) if re.search(start_re, ln))
    out = []
    for ln in lines[i:]:
        if out and ((end_re and re.search(end_re, ln)) or (not end_re and ln.strip() == "!")):
            if include_end:
                out.append(ln)
            break
        out.append(ln)
    if len(out) > max_lines:
        out = out[:max_lines] + ["! ... (shortened, see the full file)"]
    return "\n".join(out) + "\n"


def py_func(path: Path, name: str) -> str:
    src = path.read_text()
    tree = ast.parse(src)
    node = next(n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name == name)
    return "\n".join(src.splitlines()[node.lineno - 1:node.end_lineno]) + "\n"


