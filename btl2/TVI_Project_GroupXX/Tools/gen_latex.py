# ----------------------------------------------------------------------------------------- figures
def figures():
    d = OUT / "figures"
    d.mkdir(parents=True, exist_ok=True)
    from playwright.sync_api import sync_playwright
    n = 0
    with sync_playwright() as pw:
        br = pw.chromium.launch()
        for svg in sorted((ROOT / "Design/img").glob("*.svg")):
            mt = re.search(r'width="(\d+)" height="(\d+)"', svg.read_text()[:300])
            w, h = int(mt.group(1)), int(mt.group(2))
            pg = br.new_page(viewport={"width": w, "height": h})
            pg.goto(svg.resolve().as_uri())
            pg.pdf(path=str(d / (svg.stem + ".pdf")), width=f"{w}px", height=f"{h}px", print_background=True,
                   page_ranges="1")
            pg.close()
            n += 1
        br.close()
    return n


