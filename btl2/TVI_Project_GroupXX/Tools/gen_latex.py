def tables():
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    # sites / capacity
    rows = []
    for r in gd.capacity_rows():
        rows.append([tex(x) for x in r])
    cap_head = ["Site", "Users now", "Users 2030", "User cap.", "IoT cap.", "Reserved", "IPv4 aggregate", "IPv6 aggregate"]
    table("sites", "X r r r r r l l", cap_head,
          [[r[0], r[1], r[2], r[3], r[4], r[5], mono(gd.capacity_rows()[i][6]), mono(gd.capacity_rows()[i][7])]
           for i, r in enumerate(rows)],
          "Site summary: demand, addressable capacity and aggregates", "tab:sites",
          font=r"\scriptsize\setlength{\tabcolsep}{3pt}")
    # VLSM per site
    vr = gd.vlan_rows()
    for s, d in m.SITES.items():
        rs = [[str(r["vlan"]), mono(r["name"]), mono(r["cidr"]), f"{r['usable']:,}".replace(",", r"\,"), mono(r["vip"]),
               mono(r["dhcp"]) if r["dhcp"] not in ("-", "static") else r["dhcp"], mono(r["v6"])]
              for r in vr if r["site"] == d["code"]]
        table(f"vlsm_{s.lower()}", "@{}r l l r l X l@{}", ["VLAN", "Name", "IPv4 subnet", "Usable", "Gateway (VIP)", "DHCP range", "IPv6 /64"],
              rs, f"{tex(d['city'])}: IPv4 VLSM plan and IPv6 /64 per VLAN", f"tab:vlsm-{s.lower()}",
              font=r"\scriptsize\setlength{\tabcolsep}{4pt}")
    # VLAN catalogue
    rs = []
    for v in sorted(m.VLAN_NAMES):
        sites = [d["code"] for s, d in m.SITES.items() if v in m.vlans_of(s)]
        rs.append([str(v), mono(m.VLAN_NAMES[v]), tex(m.VLAN_PURPOSE[v]), tex(", ".join(sites) or "all switches")])
    table("vlans", "r l X l", ["VLAN", "Name", "Purpose", "Sites"], rs, "VLAN catalogue", "tab:vlans")
    # links
    rs = [[tex(r[0]), tex(r[1]), mono(r[2]), tex(r[3]), mono(r[4]), mono(r[5])] for r in gd.infra_rows()]
    table("links", "l l l l l l", ["Type", "Device A / interface", "IPv4 A", "Device B / interface", "IPv4 B", "Subnet"], rs,
          "Point-to-point links, overlay tunnels and provider hand-offs", "tab:links", long=True, font=r"\scriptsize")
    # devices
    rs = []
    for n, d in m.DEVICES.items():
        rs.append([mono(n), tex(m.SITES[d["site"]]["code"] if d["site"] else "provider"), tex(d["role"]),
                   tex(d.get("image", d.get("platform", ""))), mono(d["mgmt"] or "-"), tex(d["desc"])])
    table("devices", "l l l l l X", ["Hostname", "Site", "Role", "Image", "Mgmt / Lo0", "Function"], rs,
          "Device inventory of the lab", "tab:devices", font=r"\scriptsize")
    # cabling
    rs = [[str(i), mono(a), mono(ia), mono(b), mono(ib), tex(kind), tex(note)]
          for i, (a, ia, b, ib, kind, note) in enumerate(m.LINKS, 1)]
    table("wiring", "r l l l l l p{4.4cm}", ["#", "Device A", "Port", "Device B", "Port", "Type", "Note"], rs,
          "Cabling table of the EVE-NG topology", "tab:wiring", long=True, font=r"\scriptsize")
    # HSRP ownership (from the rendered configs)
    groups = {}
    for dev, c in CFG.items():
        for ifn, d in c.interfaces.items():
            for g, h in d["hsrp"].items():
                if h["vip"]:                  # IPv4 groups; each has an IPv6 twin (group + 1000)
                    groups.setdefault((m.DEVICES[dev]["site"], g, h["vip"]), []).append((h["priority"], dev))
    rs = []
    for (site, g, vip), mem in sorted(groups.items(), key=lambda x: (list(m.SITES).index(x[0][0]), x[0][1])):
        mem.sort(reverse=True)
        rs.append([tex(m.SITES[site]["code"]), str(g), mono(m.VLAN_NAMES.get(g, "")), mono(vip),
                   mono(mem[0][1]) + f" ({mem[0][0]})", mono(mem[1][1]) + f" ({mem[1][0]})"])
    table("hsrp", "l r l l l l", ["Site", "Group", "VLAN", "Virtual IP", "Active (priority)", "Standby (priority)"], rs,
          "HSRPv2 groups (IPv4; the IPv6 gateway of each VLAN is group number + 1000 with the same owner)", "tab:hsrp", long=True, font=r"\scriptsize")
    # BGP sessions (from the rendered configs)
    owner = {d["ip"].split("/")[0]: (dev, ifn) for dev, c in CFG.items() for ifn, d in c.interfaces.items() if d["ip"]}
    rs, seen = [], set()
    for dev, c in CFG.items():
        if not c.bgp:
            continue
        asn, body = c.bgp
        for ln in body:
            w = ln.split()
            if w[0] == "neighbor" and w[2] == "remote-as" and ":" not in w[1]:
                peer, pif = owner[w[1]]
                key = tuple(sorted((dev, peer)))
                if key in seen:
                    continue
                seen.add(key)
                kind = "iBGP" if w[3] == asn else "eBGP"
                rr = "RR client" if f"neighbor {w[1]} route-reflector-client" in "\n".join(body) else ""
                via = pif if pif.startswith(("Tunnel", "Loopback")) else "direct"
                rs.append([mono(dev), f"AS {asn}", mono(peer), f"AS {w[3]}", kind, tex(via), rr])
    table("bgp", "l l l l l l X", ["Router", "AS", "Peer", "Peer AS", "Type", "Transport", "Role"], rs,
          "BGP sessions (IPv4; every iBGP session has an IPv6 twin)", "tab:bgp", font=r"\scriptsize")
    # emulation results
    summ = HERE / "frr_emulation" / "results" / "summary.json"
    if summ.exists():
        j = json.loads(summ.read_text())
        rs = []
        for r in j["scenarios"]:
            worst = max(v["longest_outage_s"] for v in r["flows"].values())
            broken = sum(not v["final_ok"] for v in r["flows"].values())
            rs.append([r["id"], tex(r["title"]), "pass" if r["passed"] else r"\textbf{fail}", f"{worst}\\,s",
                       f"{broken}/{len(r['flows'])}"])
        table("emulation", "l X l r r", ["ID", "Injected failure", "Result", "Worst outage", "Flows down at end"], rs,
              "FRR emulation of the routing design: failure scenarios (supplementary evidence, not the IOSv lab)",
              "tab:emulation")


