def vlan_rows():
    rows = []
    for s, d in m.SITES.items():
        for v in m.vlans_of(s):
            n = m.net(s, v)
            usable = n.num_addresses - 2
            if v == 90:
                gw, svi1, svi2, dhcp = "-", m.host(s, 90, 1), m.host(s, 90, 2), "-"
            else:
                gw, svi1, svi2 = m.host(s, v, 1), m.host(s, v, 2), m.host(s, v, 3)
                if v in m.dhcp_vlans(s):
                    first = n.network_address + m.DHCP_EXCLUDED + 1
                    dhcp = f"{first} - {n.broadcast_address - 1}"
                else:
                    dhcp = "static"
            rows.append(dict(site=d["code"], vlan=v, name=m.VLAN_NAMES[v], zone=m.ZONE_OF.get(v, ""),
                             cidr=str(n), prefix=n.prefixlen, mask=str(n.netmask), usable=usable,
                             vip=gw, svi1=svi1, svi2=svi2, dhcp=dhcp, v6=m.v6net(s, v),
                             v6vip=m.v6host(s, v, 1), purpose=m.VLAN_PURPOSE[v]))
    return rows


def infra_rows():
    rows = []
    for (core, edge), (cif, eif, net_) in m.CORE_EDGE_P2P.items():
        a, b, mk = m.p2p_v4(core, edge)
        a6, b6 = m.p2p_v6(core, edge)
        rows.append(("Core-Edge p2p", f"{core} {cif}", a, f"{edge} {eif}", b, net_, f"{a6} / {b6} (/64)"))
    ee = m.EDGE_EDGE_P2P
    rows.append(("Edge-Edge p2p", f"{ee['a']} {ee['a_if']}", ee["a_ip"], f"{ee['b']} {ee['b_if']}", ee["b_ip"],
                 ee["net"], f"{ee['a_ip6']} / {ee['b_ip6']} (/64)"))
    for t, d in m.TUNNELS.items():
        rows.append((f"GRE/IPsec Tunnel{t} ({d['via']})", f"{d['hub']} Tunnel{t}", d["hub_ip"],
                     f"{d['spoke']} Tunnel{t}", d["spoke_ip"], d["net"],
                     f"{d['hub_ip6']} / {d['spoke_ip6']} (/64)"))
    for e, w in m.WAN.items():
        rows.append((f"WAN to {w['isp']}", f"{e} Gi0/0", w["ip"], f"{w['isp']} {w['isp_if']}", w["isp_ip"],
                     w["net"], "n/a (IPv4 transport; IPv6 rides inside IPsec)"))
    for i, w in m.ISP_NET_LINK.items():
        rows.append(("ISP transit", f"{i} {w['isp_if']}", w["isp_ip"], f"{m.NET} {w['net_if']}", w["net_ip"], w["net"], "n/a"))
    return rows


def loopback_rows():
    rows = []
    for n, d in m.DEVICES.items():
        if d["lo"] and d["site"]:
            rows.append((n, d["role"], m.loopback4(n), m.loopback6(n), d["mgmt"]))
    for n in (m.ISPA, m.ISPB, m.NET):
        rows.append((n, DEV_ROLE(n), m.ISP_LO[n], "-", m.ISP_LO[n]))
    return rows


def DEV_ROLE(n):
    return m.DEVICES[n]["role"]


def capacity_rows():
    rows = []
    for s, d in m.SITES.items():
        user_vlans = [v for v in m.SITE_VLANS[s] if v in (10, 20, 21, 30)]
        cap = sum(m.net(s, v).num_addresses - 3 for v in user_vlans)
        iot = sum(m.net(s, v).num_addresses - 3 for v in m.SITE_VLANS[s] if v in (60, 61, 62))
        res = sum(ipa.ip_network(n).num_addresses for n, _ in m.SITE_RESERVED[s])
        rows.append((d["code"], d["users_now"], d["users_2030"], cap, iot, res,
                     f"{m.SITES[s]['v4']}", f"{m.SITES[s]['v6']}"))
    return rows


def inventory_yaml():
    out = ["# Generated by Tools/gen_docs.py from Tools/tvi_model.py - do not edit by hand.",
           "# Credentials are NEVER stored here (see README: env vars / getpass / Ansible Vault).",
           "defaults:", "  port: 22", "  device_type: cisco_ios", "  timeout: 15", "", "devices:"]
    for n, d in m.DEVICES.items():
        if d["role"] in ("isp", "internet"):      # provider devices are not managed by TVI
            continue
        out += [f"  - hostname: {n}", f"    ip: {d['mgmt'] or m.DHCP_SERVER}", "    device_type: cisco_ios", "    port: 22",
                f"    site: {m.SITES[d['site']]['code']}", f"    role: {d['role']}"]
    return "\n".join(out) + "\n"


def ansible_inventory():
    groups = {"core": [], "access": [], "edge": []}
    for n, d in m.DEVICES.items():
        if d["role"] in groups:
            groups[d["role"]].append((n, d["mgmt"]))
    out = ["# Generated by Tools/gen_docs.py - credentials come from Ansible Vault / --ask-pass, never from here."]
    for g, items in groups.items():
        out.append(f"[{g}]")
        out += [f"{n} ansible_host={ip}" for n, ip in items]
        out.append("")
    out += ["[tvi:children]", *groups, "", "[tvi:vars]", "ansible_connection=network_cli",
            "ansible_network_os=ios", "ansible_become=yes", "ansible_become_method=enable", ""]
    return "\n".join(out)


def wiring_md():
    lines = ["| # | Device A | Port A | Device B | Port B | Type | Note |", "|---|---|---|---|---|---|---|"]
