COL = {"trunk": "#1f4e9c", "etherchannel": "#1f4e9c", "routed": "#222222", "wan": "#c00000",
       "access": "#7f7f7f", "ipsec": "#2e8b57", "ebgp": "#ed7d31"}
SHAPE = {"core": ("box3d", "#BDD7EE"), "access": ("box", "#DDEBF7"), "edge": ("box", "#F8CBAD"),
         "dcsrv": ("component", "#E2EFDA"), "isp": ("ellipse", "#EDEDED"), "internet": ("ellipse", "#D9D9D9"),
         "host": ("ellipse", "#FFFFFF")}


def dot_node(n):
    d = m.DEVICES.get(n)
    role = d["role"] if d else "host"
    shp, fill = SHAPE[role]
    sub = ""
    if d and d["mgmt"]:
        sub = f"\\n{d['mgmt']}"
    elif n in m.HOSTS and m.HOSTS[n]["ip"]:
        sub = f"\\n{m.HOSTS[n]['ip']}"
    elif n in m.HOSTS:
        sub = f"\\nVLAN {m.HOSTS[n]['vlan']}"
    return f'"{n}" [label="{n}{sub}", shape={shp}, style=filled, fillcolor="{fill}", fontsize=10];'


def dot_edge(a, ia, b, ib, kind, note, labels=True):
    col = COL.get(kind, "#000")
    extra = f', taillabel="{ia}", headlabel="{ib}", labelfontsize=8, labeldistance=1.6' if labels else ""
    pen = 2.5 if kind in ("etherchannel",) else 1.4
    return f'"{a}" -- "{b}" [color="{col}", penwidth={pen}{extra}, tooltip="{note}"];'


def render_dot(src, out):
    p = Path(str(out) + ".dot")
    p.write_text(src)
    subprocess.run(["dot", "-Tpng", "-Gdpi=130", str(p), "-o", str(out)], check=True)
    p.unlink()


