def svg_render(out, W, H, title, pos, links, boxes, notes=(), tunnels=()):
    """Generic hand-placed diagram: boxes, devices, links with interface IDs at both ends."""
    fills = {"core": "#BDD7EE", "access": "#DDEBF7", "edge": "#F8CBAD", "dcsrv": "#E2EFDA", "isp": "#EDEDED",
             "internet": "#D9D9D9", "host": "#FFFFFF"}
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" font-family="Helvetica, Arial, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="white"/>',
         f'<text x="{W / 2}" y="26" font-size="19" font-weight="bold" text-anchor="middle">{escape(title)}</text>']
    for lab, x, y, w, h, col in boxes:
        o.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="{col}" stroke="#777" stroke-dasharray="6 4"/>'
                 f'<text x="{x + 10}" y="{y + 18}" font-size="12.5" font-weight="bold" fill="#333">{escape(lab)}</text>')

    def halo(x, y, txt, size=10.5, col="#222", anchor="middle", bold=False):
        w = ' font-weight="bold"' if bold else ""
        o.append(f'<text x="{x:.0f}" y="{y:.0f}" font-size="{size}" fill="{col}" text-anchor="{anchor}"{w} '
                 f'paint-order="stroke" stroke="white" stroke-width="4" stroke-linejoin="round">{escape(txt)}</text>')
    ec = 0
    for (a, ia, b, ib, kind, note) in links:
        if a not in pos or b not in pos:
            continue
        (x1, y1), (x2, y2) = pos[a], pos[b]
        if kind == "etherchannel":
            off = (-11, 11)[ec % 2]
            ec += 1
            y1 += off
            y2 += off
            note = ""
        wd = {"etherchannel": 3.5, "access": 1.6}.get(kind, 2.2)
        o.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{COL[kind]}" stroke-width="{wd}"/>')
        for t, lab in ((0.2, ia), (0.8, ib)):
            halo(x1 + (x2 - x1) * t, y1 + (y2 - y1) * t - 3, lab, 10, COL[kind], bold=True)
        if kind in ("trunk", "access", "routed", "wan", "etherchannel") and note:
            halo((x1 + x2) / 2, (y1 + y2) / 2 + 4, note, 9.5, "#555")
    for (a, b, lab, curve) in tunnels:
        (x1, y1), (x2, y2) = pos[a], pos[b]
        mx, my = (x1 + x2) / 2, (y1 + y2) / 2 + curve
        o.append(f'<path d="M{x1},{y1} Q{mx},{my} {x2},{y2}" fill="none" stroke="{COL["ipsec"]}" stroke-width="3" stroke-dasharray="9 5"/>')
        halo(mx, (y1 + y2) / 2 + curve / 2 - 4, lab, 11, COL["ipsec"], bold=True)
    for n, (x, y) in pos.items():
        d = m.DEVICES.get(n)
        role = d["role"] if d else "host"
        w, h = (150, 44) if d else (130, 40)
        sub = d["mgmt"] if d else (f"VLAN {m.HOSTS[n]['vlan']}" + (f" - {m.HOSTS[n]['ip']}" if m.HOSTS[n]["ip"] else ""))
        if role in ("isp", "internet") or not d:
            o.append(f'<ellipse cx="{x}" cy="{y}" rx="{w / 2}" ry="{h / 2 + 1}" fill="{fills[role]}" stroke="#444"/>')
        else:
            o.append(f'<rect x="{x - w / 2}" y="{y - h / 2}" width="{w}" height="{h}" rx="5" fill="{fills[role]}" stroke="#444"/>')
        o.append(f'<text x="{x}" y="{y - 2}" font-size="11" font-weight="bold" text-anchor="middle">{n}</text>'
                 f'<text x="{x}" y="{y + 12}" font-size="10" text-anchor="middle" fill="#333">{sub}</text>')
    for (x, y, lines_) in notes:
        o.append(f'<rect x="{x}" y="{y}" width="330" height="{22 + 16 * len(lines_)}" fill="#FFFFF0" stroke="#999"/>')
        for i, ln in enumerate(lines_):
            o.append(f'<text x="{x + 8}" y="{y + 16 + 16 * i}" font-size="11" {"font-weight=\"bold\"" if i == 0 else ""}>{escape(ln)}</text>')
    o.append("</svg>")
    svg = Path(str(out).replace(".png", ".svg"))
    svg.write_text("\n".join(o))
    from playwright.sync_api import sync_playwright
    with sync_playwright() as pw:
        br = pw.chromium.launch()
        pg = br.new_page(viewport={"width": W, "height": H}, device_scale_factor=2)
        pg.goto(svg.resolve().as_uri())
        pg.screenshot(path=str(out))
        br.close()


