def ip_schema_xlsx(path):
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    hdr_fill = PatternFill("solid", fgColor="1F3864")
    hdr_font = Font(bold=True, color="FFFFFF")
    thin = Side(style="thin", color="BBBBBB")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    site_fill = {"HCMC": "DDEBF7", "HANOI": "E2EFDA", "DANANG": "FFF2CC"}

    def sheet(ws, title, head, rows, widths=None, site_col=None):
        ws.title = title
        ws.append(head)
        for c in ws[1]:
            c.fill, c.font, c.border = hdr_fill, hdr_font, border
            c.alignment = Alignment(wrap_text=True, vertical="center")
        for r in rows:
            ws.append(list(r))
        for row in ws.iter_rows(min_row=2):
            for c in row:
                c.border = border
                c.alignment = Alignment(vertical="top", wrap_text=True)
            if site_col is not None and row[site_col].value in site_fill:
                for c in row:
                    c.fill = PatternFill("solid", fgColor=site_fill[row[site_col].value])
        for i, w in enumerate(widths or [], 1):
            ws.column_dimensions[get_column_letter(i)].width = w
        ws.freeze_panes = "A2"

    ws = wb.active
    vr = vlan_rows()
    rows = []
    for i, r in enumerate(vr, 2):
        # usable hosts as a live formula from the prefix length
        rows.append((r["site"], r["vlan"], r["name"], r["zone"], r["cidr"], r["prefix"], r["mask"],
                     f"=2^(32-F{i})-2", r["vip"], r["svi1"], r["svi2"], r["dhcp"], r["v6"], r["v6vip"], r["purpose"]))
    sheet(ws, "IPv4 VLSM + IPv6 per VLAN",
          ["Site", "VLAN", "Name", "Zone", "IPv4 subnet", "Prefix", "Mask", "Usable hosts (formula)", "Gateway VIP (HSRP)",
           "SVI / sub-if A", "SVI / sub-if B", "DHCP range", "IPv6 /64", "IPv6 gateway VIP", "Purpose"],
          rows, [9, 7, 20, 12, 18, 7, 16, 14, 15, 15, 15, 30, 20, 20, 50], site_col=0)

    ws2 = wb.create_sheet()
    sheet(ws2, "Links, tunnels, WAN", ["Link", "End A", "IPv4 A", "End B", "IPv4 B", "Subnet", "IPv6"],
          infra_rows(), [34, 30, 16, 30, 16, 18, 48])
    ws3 = wb.create_sheet()
    sheet(ws3, "Loopbacks & mgmt", ["Device", "Role", "Loopback0 IPv4", "Loopback0 IPv6", "Management address"],
          loopback_rows(), [24, 10, 16, 26, 20])
    ws4 = wb.create_sheet()
    res = []
    for s in m.SITES:
        for n, p in list(m.SITE_RESERVED[s]) + list(m.INFRA_BLOCKS[s]):
            res.append((m.SITES[s]["code"], n, p))
    sheet(ws4, "Reserved & infra blocks", ["Site", "Block", "Purpose"], res, [10, 20, 80], site_col=0)

    ws5 = wb.create_sheet()
    caprows = []
    for i, r in enumerate(capacity_rows(), 2):
        caprows.append((r[0], r[1], r[2], r[3], r[4], f'=IF(D{i}>=B{i},"OK now","SHORT")',
                        f'=D{i}/B{i}', r[5], r[6], r[7]))
    sheet(ws5, "Capacity check",
          ["Site", "Users now", "Users 2030", "User capacity today", "IoT capacity", "Today", "Capacity / users now (x)", "Reserved addresses",
           "IPv4 aggregate", "IPv6 aggregate"], caprows, [10, 11, 11, 18, 14, 10, 18, 16, 16, 18], site_col=0)
    ws6 = wb.create_sheet()
    sheet(ws6, "Autonomous systems", ["AS", "Owner", "Role"],
          [(m.AS_TVI, "TVI", "iBGP/RR over GRE/IPsec"), (m.AS_ISP_A, "ISP-A", "eBGP default"),
           (m.AS_ISP_B, "ISP-B", "eBGP default"), (m.AS_NET, "INTERNET", "SaaS stand-in 8.8.8.8")], [10, 14, 40])
    wb.save(path)


