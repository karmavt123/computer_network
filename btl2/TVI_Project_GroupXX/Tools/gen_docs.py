def _page(name, pos, links, groups, tunnels=(), pid="p"):
    cells = ['<mxCell id="0"/>', '<mxCell id="1" parent="0"/>']
    nid = {}
    k = 2
    for (label, x, y, w, h, color) in groups:
        cells.append(f'<mxCell id="{k}" value="{escape(label)}" style="rounded=1;whiteSpace=wrap;html=1;fillColor={color};'
                     f'strokeColor=#888888;dashed=1;verticalAlign=top;align=left;spacingLeft=8;fontStyle=1;opacity=40;" vertex="1" parent="1">'
                     f'<mxGeometry x="{x}" y="{y}" width="{w}" height="{h}" as="geometry"/></mxCell>')
        k += 1
    for n, (x, y) in pos.items():
        d = m.DEVICES.get(n)
        role = d["role"] if d else "host"
        st = DRAWIO_STYLE[role]
        sub = ""
        if d and d["mgmt"]:
            sub = f"<br/><font style='font-size:9px'>{d['mgmt']}</font>"
        elif n in m.HOSTS:
            hd = m.HOSTS[n]
            sub = f"<br/><font style='font-size:9px'>VLAN {hd['vlan']}{' ' + hd['ip'] if hd['ip'] else ''}</font>"
        cells.append(f'<mxCell id="{k}" value="{escape(n)}{escape(sub) if False else sub}" '
                     f'style="{st}html=1;whiteSpace=wrap;verticalLabelPosition=bottom;verticalAlign=top;align=center;fontSize=11;" '
                     f'vertex="1" parent="1"><mxGeometry x="{x}" y="{y}" width="70" height="60" as="geometry"/></mxCell>')
        nid[n] = k
        k += 1
    for (a, ia, b, ib, kind, note) in links:
        if a in nid and b in nid:
            lab = f"{ia} - {ib}" + (f"&#10;{note}" if kind in ("trunk", "access", "routed", "wan") else "")
            cells.append(f'<mxCell id="{k}" value="{lab}" style="endArrow=none;html=1;fontSize=8;{EDGE_STYLE[kind]}" '
                         f'edge="1" parent="1" source="{nid[a]}" target="{nid[b]}"><mxGeometry relative="1" as="geometry"/></mxCell>')
            k += 1
    for (a, b, lab) in tunnels:
        if a in nid and b in nid:
            cells.append(f'<mxCell id="{k}" value="{escape(lab)}" style="endArrow=none;html=1;fontSize=8;{EDGE_STYLE["ipsec"]}curved=1;" '
                         f'edge="1" parent="1" source="{nid[a]}" target="{nid[b]}"><mxGeometry relative="1" as="geometry"/></mxCell>')
            k += 1
    return (f'<diagram id="{pid}" name="{escape(name)}"><mxGraphModel dx="1400" dy="900" grid="1" gridSize="10" page="1" '
            f'pageWidth="1600" pageHeight="1000"><root>' + "".join(cells) + "</root></mxGraphModel></diagram>")


