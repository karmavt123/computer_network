def gen_core(name):
    which = 1 if name == m.CORE1 else 2
    site = "HQ"
    c = Cfg()
    header(c, name, f"HQ collapsed core #{which} - L3 gateway, HSRP, OSPF/OSPFv3, LACP to peer core")
    baseline(c, name, "switch")
    c.a("ip routing", "ipv6 unicast-routing", "ipv6 cef", "!")
    vl = vlans_of(site)
    vlan_db(c, vl)
    mine = [v for v in vl if m.core_active_sw01(v) == (which == 1)]
    other = [v for v in vl if v not in mine]
    c.a("! ---- Spanning tree: RSTP (rapid-PVST+), deterministic root placement ----",
        "spanning-tree mode rapid-pvst",
        "spanning-tree extend system-id",
        "spanning-tree vlan " + ",".join(map(str, mine)) + " priority 4096",
        "spanning-tree vlan " + ",".join(map(str, other)) + " priority 8192",
        "spanning-tree loopguard default",
        "errdisable recovery cause bpduguard psecure-violation",
        "errdisable recovery interval 300",
        "!",
        "track timer ip route 1",
        "track 1 ip route 0.0.0.0 0.0.0.0 reachability",
        "!")
    acl_block(c)
    c.a("interface Loopback0",
        f" description Router-ID / management",
        f" ip address {m.loopback4(name)} 255.255.255.255",
        f" ipv6 address {m.loopback6(name)}/128",
        " ip ospf 10 area 0", " ospfv3 10 ipv6 area 0", "!")
    # Port-channel to peer core
    allowed = ",".join(map(str, [v for v in vl if v != 90] + [90]))
    c.a("interface Port-channel1",
        f" description PO1 LACP to {m.CORE2 if which == 1 else m.CORE1}",
        " switchport trunk encapsulation dot1q", " switchport mode trunk",
        " switchport trunk native vlan 998",
        f" switchport trunk allowed vlan {','.join(map(str, sorted(vl)))}",
        " switchport nonegotiate", " no shutdown", "!")
    for ifn in ("Gi0/0", "Gi0/1"):
        c.a(f"interface GigabitEthernet{ifn[2:]}",
            f" description PO1 member -> {m.CORE2 if which == 1 else m.CORE1} {ifn}",
            " switchport trunk encapsulation dot1q", " switchport mode trunk",
            " switchport trunk native vlan 998", " switchport nonegotiate",
            " channel-protocol lacp", " channel-group 1 mode active", " no shutdown", "!")
    trunk_vlans = ",".join(map(str, [v for v in sorted(vl) if v != 90]))
    for (da, ia, db, ib, kind, note) in LINKS:
        if da == name and kind == "trunk":
            c.a(f"interface GigabitEthernet{ia[2:]}",
                f" description TRUNK -> {db} {ib}",
                " switchport trunk encapsulation dot1q", " switchport mode trunk",
                " switchport trunk native vlan 998",
                f" switchport trunk allowed vlan {trunk_vlans}",
                " switchport nonegotiate",
                " spanning-tree guard root",
                " no shutdown", "!")
    # routed links to edge routers
    for (core, edge), (cif, eif, _) in m.CORE_EDGE_P2P.items():
        if core != name:
            continue
        a4, b4, mk = m.p2p_v4(core, edge)
        a6, b6 = m.p2p_v6(core, edge)
        c.a(f"interface GigabitEthernet{cif[2:]}",
            f" description L3 -> {edge} {eif}",
            " no switchport",
            f" ip address {a4} {mk}",
            f" ipv6 address {a6}/64",
            " ip ospf network point-to-point", " ip ospf 10 area 0", *OSPF_FAST,
            " ospfv3 10 network point-to-point", " ospfv3 10 ipv6 area 0", *OSPF3_FAST,
            " no shutdown", "!")
    used = {ia for (da, ia, *_r) in LINKS if da == name} | {ib for (*_r1, db, ib, _k, _n) in LINKS if db == name}
    for p in ("Gi1/2", "Gi1/3"):
        if p not in used:
            c.a(f"interface GigabitEthernet{p[2:]}", " description UNUSED", " switchport mode access",
                " switchport access vlan 999", " shutdown", "!")
    # SVIs
    for v in sorted(vl):
        if v == 90:
            c.a("interface Vlan90",
                " description L3 transit between core switches",
                f" ip address {host(site, 90, which)} {mask(site, 90)}",
                f" ipv6 address {m.v6host(site, 90, which)}/64",
                " ip ospf network point-to-point", " ip ospf 10 area 0", *OSPF_FAST,
                " ospfv3 10 network point-to-point", " ospfv3 10 ipv6 area 0", *OSPF3_FAST,
                " no shutdown", "!")
            continue
        gateway_block(c, site, v, which, m.core_active_sw01(v) == (which == 1),
                      [f"interface Vlan{v}"], 1)
    c.a("!", "! ---- Routing: OSPF (IPv4) + OSPFv3 (IPv6), area 0, default originated by the edge routers ----",
        "router ospf 10",
        f" router-id {m.loopback4(name)}",
        " passive-interface default",
        " no passive-interface Vlan90", " no passive-interface GigabitEthernet1/0",
        " no passive-interface GigabitEthernet1/1",
        " auto-cost reference-bandwidth 10000",
        "router ospfv3 10",
        f" router-id {m.loopback4(name)}",
        " address-family ipv6 unicast",
        "  passive-interface default",
        "  no passive-interface Vlan90", "  no passive-interface GigabitEthernet1/0",
        "  no passive-interface GigabitEthernet1/1",
        "  auto-cost reference-bandwidth 10000",
        " exit-address-family",
        "!")
    post_load(c, name)
    _clean(c)
    return c.text()


