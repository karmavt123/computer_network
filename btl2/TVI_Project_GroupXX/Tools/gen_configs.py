def header(c: Cfg, name: str, note: str):
    d = DEVICES[name]
    c.a(f"! ======================================================================",
        f"! {name}  -  {d['desc']}",
        f"! Image: Cisco {d['image']} (EVE-NG)   |   {note}",
        f"! Generated by Tools/gen_configs.py from Tools/tvi_model.py - do not edit by hand.",
        "! ======================================================================",
        "!")


def baseline(c: Cfg, name: str, kind: str, ntp: bool = True):
    """AAA, SSH, NTP, syslog, banner, hardening (kind = 'router' | 'switch')."""
    c.a("hostname " + name, "!",
        "service timestamps debug datetime msec localtime",
        "service timestamps log datetime msec localtime",
        "service password-encryption",
        "no service pad",
        "no ip domain-lookup",
        f"ip domain-name {m.DOMAIN}",
        "no ip source-route",
        "no ip http server",
        "no ip http secure-server",
        "ip cef",
        "!",
        "! ---- AAA / local accounts (type-5 hashes, no clear-text secrets) ----",
        "aaa new-model",
        "aaa authentication login default local",
        "aaa authentication login CONSOLE none",
        "aaa authorization exec default local",
        f"enable secret 5 {m.SECRET5}",
        f"username {m.ADMIN_USER} privilege 15 secret 5 {m.SECRET5}",
        "!",
        "clock timezone ICT 7 0")
    if ntp:
        c.a(f"ntp server {m.NTP_SERVER}")
    c.a(f"logging host {m.SYSLOG_HOST}",
        "logging trap informational",
        "logging buffered 16384",
        "!",
        f"banner motd # {m.BANNER} #",
        "!",
        "ip ssh version 2",
        "ip ssh time-out 60",
        "ip ssh authentication-retries 3",
        "ip access-list standard VTY-MGMT")
    for n in m.MGMT_NETS:
        c.a(" permit " + m.wild(n))
    c.a(" deny any log",
        "!",
        "line con 0",
        " exec-timeout 30 0",
        " logging synchronous",
        " login authentication CONSOLE",
        "line vty 0 4",
        " access-class VTY-MGMT in",
        " exec-timeout 10 0",
        " logging synchronous",
        " transport input ssh",
        "!")
    if kind == "router":
        c.a("ipv6 unicast-routing", "ipv6 cef", "!")


def vlan_db(c: Cfg, vlans):
    c.a("vtp mode transparent", "!")
    for v in sorted(set(vlans) | {998, 999}):
        c.a(f"vlan {v}", f" name {VLAN_NAMES[v]}")
    c.bang()


def post_load(c: Cfg, name: str):
    c.a("!", "! ---------------------------------------------------------------------------",
        "! POST-LOAD (exec mode, once per device - key generation cannot live in a startup-config):",
        "!   crypto key generate rsa general-keys modulus 2048",
        "!   copy running-config startup-config",
        "end")


# --------------------------------------------------------------------------------------
# ACLs (identical on every L3 device so policy follows the user wherever the gateway is)
# --------------------------------------------------------------------------------------
def acl_block(c: Cfg):
    ex, mg, iot = m.EXEC_NETS, m.MGMT_NETS, m.IOT_NETS
    c.a("! ---- Segmentation ACLs (micro-segmentation at the first L3 hop) ----")

    def deny_to(nets, remark=None):
        for n in nets:
            c.a(f" deny   ip any {m.wild(n)}")

    c.a("ip access-list extended ACL-EXEC-IN",
        " remark Executives/Finance: reach everything except network management")
    deny_to(mg)
    c.a(" permit ip any any")

    for nm, with_iot in (("ACL-CORP-IN", False), ("ACL-LOGISTICS-IN", True)):
        c.a(f"ip access-list extended {nm}",
            " remark Corporate users: servers + Internet; EXEC/FINANCE and MGMT protected (replies allowed)")
        for n in ex:
            c.a(f" permit tcp any {m.wild(n)} established",
                f" permit icmp any {m.wild(n)} echo-reply")
        deny_to(ex)
        deny_to(mg)
        if not with_iot:
            deny_to(iot)
        c.a(" permit ip any any")

    c.a("ip access-list extended ACL-GUEST-IN",
        " remark Guests: DHCP + Internet only, no RFC1918 destination at all",
        " permit udp any eq bootpc any eq bootps",
        " permit udp any host 224.0.0.102 eq 1985",
        " deny   ip any 10.0.0.0 0.255.255.255",
        " deny   ip any 172.16.0.0 0.15.255.255",
        " deny   ip any 192.168.0.0 0.0.255.255",
        " permit ip any any")

    c.a("ip access-list extended ACL-IOT-IN",
        " remark IoT: DHCP/DNS/NTP + IoT platform (MQTT-TLS/HTTPS) only; no lateral movement, no Internet",
        " permit udp any eq bootpc any eq bootps",
        " permit udp any host 224.0.0.102 eq 1985",
        f" permit udp any host {m.DHCP_SERVER} eq domain",
        f" permit udp any host {m.NTP_SERVER} eq ntp",
        f" permit icmp any host {m.DHCP_SERVER} echo",
        f" permit tcp any host {m.IOT_PLATFORM} eq 8883",
        f" permit tcp any host {m.IOT_PLATFORM} eq 443",
        " permit tcp any any established",
        " permit icmp any any echo-reply",
        " deny   ip any any log")

    # ---- IPv6 ----
    s = SITES
    ex6 = [m.v6net(s_, 10) for s_ in SITES]
    mg6 = [m.v6net(s_, 99) for s_ in SITES]
    iot6 = [m.v6net(s_, v) for s_ in SITES for v in (60, 61, 62) if v in SITE_VLANS[s_]]
    c.a("!")
    c.a("ipv6 access-list ACL6-EXEC-IN")
    for n in mg6:
        c.a(f" deny ipv6 any {n}")
    c.a(" permit ipv6 any any")
    for nm, with_iot in (("ACL6-CORP-IN", False), ("ACL6-LOGISTICS-IN", True)):
        c.a(f"ipv6 access-list {nm}")
        for n in ex6:
            c.a(f" permit tcp any {n} established", f" deny ipv6 any {n}")
        for n in mg6:
            c.a(f" deny ipv6 any {n}")
        if not with_iot:
            for n in iot6:
                c.a(f" deny ipv6 any {n}")
        c.a(" permit ipv6 any any")
    c.a("ipv6 access-list ACL6-GUEST-IN",
        " deny ipv6 any 2001:db8::/32",
        " deny ipv6 any FC00::/7",
        " permit ipv6 any any",
        "ipv6 access-list ACL6-IOT-IN",
        " remark an explicit final deny also removes the implicit neighbour-discovery permits: allow ND explicitly",
        " permit icmp any any nd-ns",
        " permit icmp any any nd-na",
        " permit icmp any any router-solicitation",
        " permit udp any any eq 2029",
        " permit udp any eq 546 any eq 547",
        f" permit tcp any host {m.v6host('HQ', 100, 20)} eq 8883",
        f" permit tcp any host {m.v6host('HQ', 100, 20)} eq 443",
        " permit tcp any any established",
        " deny ipv6 any any log",
        "!")


