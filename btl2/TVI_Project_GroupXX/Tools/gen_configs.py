"""
gen_configs.py - renders every startup-config from tvi_model.py.

    python3 Tools/gen_configs.py            # writes ./Configurations/**
    TVI_LAB_PASSWORD='...' python3 Tools/gen_configs.py   # change lab secrets

Output files are plain IOS text, ready to be pasted into the console of the EVE-NG node
(or pushed with Lab/push_configs.py).
"""
