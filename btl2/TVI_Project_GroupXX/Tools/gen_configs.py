def gen_edge(name):
    d = DEVICES[name]
    site = d["site"]
    hq = site == "HQ"
    primary = name.endswith("01")
    which = 1 if primary else 2
    w = WAN[name]
    lo4_, lo6_ = m.loopback4(name), m.loopback6(name)
    agg4, agg6 = SITES[site]["v4"], SITES[site]["v6"]
    n_ = ipa_net(agg4)
    c = Cfg()
    header(c, name, ("HQ WAN edge / IPsec hub / BGP route-reflector" if hq else "Branch gateway / IPsec spoke") +
           f" - uplink {w['isp']}")
    baseline(c, name, "router")
    if not hq:
        # IOS polls 'ip route' track objects every 15 s by default - far too slow for a gateway failover
        c.a("track timer ip route 1",
            f"track 1 ip route {m.SITES['HQ']['v4'].split('/')[0]} 255.255.0.0 reachability", "!")
    qos_block(c)
    acl_block(c)
    nat_zbf_block(c)
    ipsec_block(c, name)
    c.a("interface Loopback0", " description Router-ID / management",
        f" ip address {lo4_} 255.255.255.255", f" ipv6 address {lo6_}/128",
        " ip ospf 10 area 0", " ospfv3 10 ipv6 area 0", "!")
    c.a("interface GigabitEthernet0/0",
        f" description WAN -> {w['isp']} {w['isp_if']} ({w['net']})",
        f" ip address {w['ip']} {w['mask']}",
        " ip nat outside", " zone-member security OUTSIDE",
        " ip verify unicast source reachable-via rx allow-default",
        " service-policy output PM-WAN-PARENT",
        " no shutdown", "!")
    if hq:
        for (core, edge), (cif, eif, _) in m.CORE_EDGE_P2P.items():
            if edge != name:
                continue
            a4, b4, mk = m.p2p_v4(core, edge)
            a6, b6 = m.p2p_v6(core, edge)
            c.a(f"interface GigabitEthernet{eif[2:]}",
                f" description L3 -> {core} {cif}",
                f" ip address {b4} {mk}", f" ipv6 address {b6}/64",
                " ip nat inside", " zone-member security INSIDE",
                " service-policy input PM-MARK-IN",
                " ip ospf network point-to-point", " ip ospf 10 area 0", *OSPF_FAST,
                " ospfv3 10 network point-to-point", " ospfv3 10 ipv6 area 0", *OSPF3_FAST,
                " no shutdown", "!")
        ee = m.EDGE_EDGE_P2P
        mine, peer_ = ("a", "b") if name == ee["a"] else ("b", "a")
        c.a("interface GigabitEthernet0/3",
            f" description L3 -> {ee[peer_]} {ee[peer_ + '_if']} (edge-to-edge: iBGP next-hops never transit the core)",
            f" ip address {ee[mine + '_ip']} {ee['mask']}", f" ipv6 address {ee[mine + '_ip6']}/64",
            " ip nat inside", " zone-member security INSIDE",
            " ip ospf network point-to-point", " ip ospf 10 area 0", *OSPF_FAST,
            " ospfv3 10 network point-to-point", " ospfv3 10 ipv6 area 0", *OSPF3_FAST,
            " no shutdown", "!")
    else:
        sw = m.HN_SW if site == "HN" else m.DN_SW
        c.a("interface GigabitEthernet0/1", f" description TRUNK (router-on-a-stick) -> {sw}",
            " no ip address", " no shutdown", "!")
        for v in [v for v in vlans_of(site) if v not in (90, 100)]:
            act = m.branch_active_e1(site, v) == primary
            hdr = [f"interface GigabitEthernet0/1.{v}", f" encapsulation dot1Q {v}"]
            gateway_block(c, site, v, which, act, hdr, 1, edge_router=True, nat=True, mark=True)
        c.a("interface GigabitEthernet0/2", " description UNUSED", " shutdown", "!",
            "interface GigabitEthernet0/3", " description UNUSED", " shutdown", "!")
    # static discard routes = summary anchors for BGP
    c.a("! ---- Summary anchors (null routes) + NAT ----",
        f"ip route {agg4.split('/')[0]} 255.255.0.0 Null0 name TVI-{SITES[site]['code']}-SUMMARY",
        f"ipv6 route {agg6} Null0 name TVI-{SITES[site]['code']}-SUMMARY6",
        f"ip nat inside source list ACL-NAT interface GigabitEthernet0/0 overload",
        "!")
    # ---- OSPF
    c.a("! ---- Underlay: OSPF/OSPFv3 area 0 inside the site ----",
        "router ospf 10", f" router-id {lo4_}", " passive-interface default",
        " auto-cost reference-bandwidth 10000")
    if hq:
        c.a(" no passive-interface GigabitEthernet0/1", " no passive-interface GigabitEthernet0/2",
            " no passive-interface GigabitEthernet0/3",
            f" default-information originate metric {10 if primary else 20} metric-type 1")
    else:
        c.a(" no passive-interface GigabitEthernet0/1.99")
    c.a("router ospfv3 10", f" router-id {lo4_}", " address-family ipv6 unicast",
        "  passive-interface default", "  auto-cost reference-bandwidth 10000")
    if hq:
        c.a("  no passive-interface GigabitEthernet0/1", "  no passive-interface GigabitEthernet0/2",
            "  no passive-interface GigabitEthernet0/3",
            f"  default-information originate always metric {10 if primary else 20} metric-type 1")
    else:
        c.a("  no passive-interface GigabitEthernet0/1.99")
    c.a(" exit-address-family", "!")
    # ---- BGP
    isp_asn = w["asn"]
    c.a("! ---- Overlay/WAN: eBGP to the ISP, iBGP over the IPsec tunnels (HQ = route-reflector) ----",
        "ip prefix-list PL-ISP-IN seq 5 permit 0.0.0.0/0",
        "ip prefix-list PL-NONE-OUT seq 5 deny 0.0.0.0/0 le 32")
    for i, s_ in enumerate(SITES, 1):
        c.a(f"ip prefix-list PL-TVI-AGG seq {i * 5} permit {SITES[s_]['v4']}")
        c.a(f"ipv6 prefix-list PL6-TVI-AGG seq {i * 5} permit {SITES[s_]['v6']}")
    c.a("ipv6 prefix-list PL6-ISP-IN seq 5 deny ::/0 le 128",
        "route-map RM-LOCALPREF permit 10",
        f" set local-preference {200 if primary else 150}",
        "!")
    bgp = [f"router bgp {m.AS_TVI}", f" bgp router-id {lo4_}", " bgp log-neighbor-changes",
           " no bgp default ipv4-unicast"]
    v4_nb, v6_nb = [], []  # (neighbor, kind)
    bgp += [f" neighbor {w['isp_ip']} remote-as {isp_asn}",
            f" neighbor {w['isp_ip']} description eBGP {w['isp']}",
            f" neighbor {w['isp_ip']} password {m.BGP_KEY}",
            f" neighbor {w['isp_ip']} timers 3 9"]
    if hq:
        peer = m.E2 if primary else m.E1
        bgp += [f" neighbor {m.loopback4(peer)} remote-as {m.AS_TVI}",
                f" neighbor {m.loopback4(peer)} description iBGP {peer}",
                f" neighbor {m.loopback4(peer)} password {m.BGP_KEY}",
                f" neighbor {m.loopback4(peer)} update-source Loopback0",
                # fast hold time on the edge-to-edge session too: the peer's loopback lies inside the Null0
                # summary, so BGP next-hop tracking alone never invalidates its routes when the peer dies
                f" neighbor {m.loopback4(peer)} timers 3 9",
                f" neighbor {m.loopback6(peer)} remote-as {m.AS_TVI}",
                f" neighbor {m.loopback6(peer)} description iBGPv6 {peer}",
                f" neighbor {m.loopback6(peer)} password {m.BGP_KEY}",
                f" neighbor {m.loopback6(peer)} update-source Loopback0",
                f" neighbor {m.loopback6(peer)} timers 3 9"]
    for t, td in m.tunnels_of(name).items():
        ip4 = td["spoke_ip"] if hq else td["hub_ip"]
        ip6 = td["spoke_ip6"] if hq else td["hub_ip6"]
        other = td["spoke"] if hq else td["hub"]
        bgp += [f" neighbor {ip4} remote-as {m.AS_TVI}", f" neighbor {ip4} description iBGP {other} (Tunnel{t})",
                f" neighbor {ip4} password {m.BGP_KEY}", f" neighbor {ip4} timers 3 9",
                f" neighbor {ip6} remote-as {m.AS_TVI}", f" neighbor {ip6} description iBGPv6 {other} (Tunnel{t})",
                f" neighbor {ip6} password {m.BGP_KEY}", f" neighbor {ip6} timers 3 9"]
    # address-family ipv4
    bgp += [" !", " address-family ipv4", f"  network {agg4.split('/')[0]} mask 255.255.0.0",
            f"  neighbor {w['isp_ip']} activate",
            f"  neighbor {w['isp_ip']} prefix-list PL-ISP-IN in",
            f"  neighbor {w['isp_ip']} prefix-list PL-NONE-OUT out"]
    if hq:
        bgp += [f"  neighbor {m.loopback4(peer)} activate",
                f"  neighbor {m.loopback4(peer)} next-hop-self all",
                f"  neighbor {m.loopback4(peer)} prefix-list PL-TVI-AGG out"]
    for t, td in m.tunnels_of(name).items():
        ip4 = td["spoke_ip"] if hq else td["hub_ip"]
        bgp += [f"  neighbor {ip4} activate", f"  neighbor {ip4} prefix-list PL-TVI-AGG out"]
        if hq:
            bgp += [f"  neighbor {ip4} route-reflector-client", f"  neighbor {ip4} next-hop-self all"]
        else:
            bgp += [f"  neighbor {ip4} route-map RM-LOCALPREF out"]
    bgp += [" exit-address-family", " !", " address-family ipv6", f"  network {agg6}"]
    if hq:
        bgp += [f"  neighbor {m.loopback6(peer)} activate",
                f"  neighbor {m.loopback6(peer)} next-hop-self all",
                f"  neighbor {m.loopback6(peer)} prefix-list PL6-TVI-AGG out"]
    for t, td in m.tunnels_of(name).items():
        ip6 = td["spoke_ip6"] if hq else td["hub_ip6"]
        bgp += [f"  neighbor {ip6} activate", f"  neighbor {ip6} prefix-list PL6-TVI-AGG out"]
        if hq:
            bgp += [f"  neighbor {ip6} route-reflector-client", f"  neighbor {ip6} next-hop-self all"]
        else:
            bgp += [f"  neighbor {ip6} route-map RM-LOCALPREF out"]
    bgp += [" exit-address-family", "!"]
    c.a(*bgp)
    post_load(c, name)
    _clean(c)
    return c.text()


def ipa_net(x):
    import ipaddress
    return ipaddress.ip_network(x)


