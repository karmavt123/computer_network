def qos_block(c: Cfg):
    c.a("! ---- QoS: classify + re-mark at the edge (never trust endpoint DSCP), LLQ on the WAN ----",
        "ip access-list extended QOS-VOICE-RTP")
    for n in m.VOICE_NETS:
        c.a(f" permit udp {m.wild(n)} any range 16384 32767")
    c.a("ip access-list extended QOS-VIDEO",
        " permit udp 10.0.0.0 0.255.255.255 any range 3478 3481",
        "ip access-list extended QOS-SIGNALING",
        " permit tcp 10.0.0.0 0.255.255.255 any eq 5060",
        " permit tcp 10.0.0.0 0.255.255.255 any eq 5061",
        " permit tcp 10.0.0.0 0.255.255.255 any eq 2000",
        " permit udp 10.0.0.0 0.255.255.255 any eq 5060",
        "class-map match-any CM-IN-VOICE", " match access-group name QOS-VOICE-RTP",
        "class-map match-any CM-IN-VIDEO", " match access-group name QOS-VIDEO",
        "class-map match-any CM-IN-SIGNALING", " match access-group name QOS-SIGNALING",
        "policy-map PM-MARK-IN",
        " class CM-IN-VOICE", "  set dscp ef",
        " class CM-IN-VIDEO", "  set dscp af31",
        " class CM-IN-SIGNALING", "  set dscp cs3",
        " class class-default", "  set dscp default",
        "class-map match-any CM-VOICE", " match dscp ef",
        "class-map match-any CM-VIDEO", " match dscp af31",
        "class-map match-any CM-SIGNALING", " match dscp cs3",
        "class-map match-any CM-NET-CTRL", " match dscp cs6",
        "policy-map PM-WAN-CHILD",
        " class CM-VOICE", "  priority percent 20",
        " class CM-VIDEO", "  bandwidth percent 25",
        " class CM-SIGNALING", "  bandwidth percent 5",
        " class CM-NET-CTRL", "  bandwidth percent 5",
        " class class-default", "  fair-queue",
        f"policy-map PM-WAN-PARENT",
        " class class-default",
        f"  shape average {m.WAN_RATE_BPS}",
        "  service-policy PM-WAN-CHILD",
        "!")


def nat_zbf_block(c: Cfg):
    c.a("! ---- NAT overload (local Internet breakout) ----",
        "ip access-list extended ACL-NAT",
        " remark never translate corporate-to-corporate traffic (fails closed if the VPN is down)",
        " deny   ip 10.0.0.0 0.255.255.255 10.0.0.0 0.255.255.255",
        " permit ip 10.0.0.0 0.255.255.255 any",
        "!",
        "! ---- Zone-based firewall: INSIDE / OUTSIDE (Internet) / VPN (site-to-site tunnels) ----",
        "! (If your IOSv image has no ZBF/security licence, delete this block and the zone-member lines.)",
        "zone security INSIDE", "zone security OUTSIDE", "zone security VPN",
        "ip access-list extended ACL-ZB-OUT-TO-SELF",
        " permit esp any any",
        " permit gre any any",
        " permit udp any any eq isakmp",
        " permit udp any any eq non500-isakmp",
        " permit tcp any any eq bgp",
        " permit tcp any eq bgp any",
        " permit icmp any any echo",
        " permit icmp any any echo-reply",
        " permit icmp any any ttl-exceeded",
        " permit icmp any any unreachable",
        "class-map type inspect match-any CM-ZB-TRAFFIC",
        " match protocol tcp", " match protocol udp", " match protocol icmp",
        "class-map type inspect match-any CM-ZB-OUT-SELF",
        " match access-group name ACL-ZB-OUT-TO-SELF",
        "policy-map type inspect PM-ZB-INSPECT",
        " class type inspect CM-ZB-TRAFFIC", "  inspect",
        " class class-default", "  drop",
        "policy-map type inspect PM-ZB-OUT-SELF",
        " class type inspect CM-ZB-OUT-SELF", "  pass",
        " class class-default", "  drop",
        "policy-map type inspect PM-ZB-PASS",
        " class class-default", "  pass",
        "zone-pair security ZP-INSIDE-OUTSIDE source INSIDE destination OUTSIDE",
        " service-policy type inspect PM-ZB-INSPECT",
        "zone-pair security ZP-OUTSIDE-SELF source OUTSIDE destination self",
        " service-policy type inspect PM-ZB-OUT-SELF",
        "zone-pair security ZP-INSIDE-VPN source INSIDE destination VPN",
        " service-policy type inspect PM-ZB-PASS",
        "zone-pair security ZP-VPN-INSIDE source VPN destination INSIDE",
        " service-policy type inspect PM-ZB-PASS",
        "!")


def ipsec_block(c: Cfg, name: str):
    peers = []
    for t, d in m.tunnels_of(name).items():
        peers.append(d["spoke_out"] if d["hub"] == name else d["hub_out"])
    c.a("! ---- GRE tunnels protected by IPsec (IKEv1 PSK, AES-256 / SHA-256 / DH14) ----",
        "! GRE carries IPv4 AND IPv6 (an IKEv1 'tunnel mode ipsec ipv4' VTI would carry IPv4 only);",
        "! IPsec runs in transport mode because GRE already supplies the outer IP header.",
        "crypto isakmp policy 10",
        " encryption aes 256", " hash sha256", " authentication pre-share", " group 14",
        " lifetime 28800",
        "crypto isakmp keepalive 10 3 periodic")
    for p in peers:
        c.a(f"crypto isakmp key {m.IPSEC_PSK} address {p}")
    c.a("crypto ipsec transform-set TVI-TS esp-aes 256 esp-sha256-hmac",
        " mode transport",
        "crypto ipsec profile TVI-IPSEC-PROFILE",
        " set transform-set TVI-TS",
        "!")
    for t, d in m.tunnels_of(name).items():
        hub = d["hub"] == name
        other = d["spoke"] if hub else d["hub"]
        c.a(f"interface Tunnel{t}",
            f" description GRE/IPsec to {other} via {d['via']}",
            f" ip address {d['hub_ip' if hub else 'spoke_ip']} {d['mask']}",
            f" ipv6 address {d['hub_ip6' if hub else 'spoke_ip6']}/64",
            " ip mtu 1400",
            " ip tcp adjust-mss 1360",
            " ipv6 mtu 1400",
            " ipv6 tcp adjust-mss 1340",
            " tunnel source GigabitEthernet0/0",
            " tunnel mode gre ip",
            f" tunnel destination {d['spoke_out' if hub else 'hub_out']}",
            " tunnel protection ipsec profile TVI-IPSEC-PROFILE",
            " zone-member security VPN",
            " no shutdown",
            "!")


# Fast OSPF hellos on every interface that forms an adjacency.  In a virtual lab (and across any L2 device) a
# failed neighbour does not take the local link down, so the default 10 s / 40 s timers mean a 40 s outage.
OSPF_FAST = [" ip ospf hello-interval 1", " ip ospf dead-interval 4"]
OSPF3_FAST = [" ospfv3 10 hello-interval 1", " ospfv3 10 dead-interval 4"]


# --------------------------------------------------------------------------------------
# Gateway interface block (HQ SVIs and branch sub-interfaces)
# --------------------------------------------------------------------------------------
def gateway_block(c, site, vlan, which, active, header_lines, track_id, *, edge_router=False, nat=False,
                  mark=False, ospf=True):
    helper = vlan in dhcp_vlans(site)
    c.a(*header_lines)
    c.a(f" description {VLAN_NAMES[vlan]} gateway")
    c.a(f" ip address {host(site, vlan, which + 1)} {mask(site, vlan)}")
    if helper:
        c.a(f" ip helper-address {m.DHCP_SERVER}")
    acl = m.acl_name_for(vlan)
    if acl:
        c.a(f" ip access-group {acl} in")
    c.a(f" ipv6 address {v6host(site, vlan, which + 1)}/64")
    if helper:
        c.a(" ipv6 nd other-config-flag",
            f" ipv6 dhcp relay destination {m.DHCP_SERVER6}")
    acl6 = m.acl6_name_for(vlan)
    if acl6:
        c.a(f" ipv6 traffic-filter {acl6} in")
    if mark and vlan in (10, 20, 21, 30, 40):
        c.a(" service-policy input PM-MARK-IN")
    if nat and vlan != 99:
        c.a(" ip nat inside")
    if edge_router:
        c.a(" zone-member security INSIDE")
    if ospf:
        c.a(" ip ospf 10 area 0", " ospfv3 10 ipv6 area 0")
        if edge_router and vlan == 99:          # the only non-passive OSPF interface of a branch router
            c.a(*OSPF_FAST, *OSPF3_FAST)
    # HSRP version 2.  IPv4 and IPv6 are two separate groups: an IOS HSRP group has ONE address family, so the
    # IPv6 gateway uses group <vlan + 1000> (HSRPv2 group range 0-4095) with the same priority/preempt/track.
    def hsrp(group):
        return [f" standby {group} priority {110 if active else 100}",
                # the designed-active router waits 60 s before it reclaims the role (lets OSPF/BGP converge first);
                # the designed-standby router must take over at once when the active's tracked priority drops
                f" standby {group} preempt delay minimum 60" if active else f" standby {group} preempt",
                f" standby {group} timers msec 500 msec 1500",
                f" standby {group} authentication md5 key-string {m.HSRP_KEY}",
                f" standby {group} track {track_id} decrement 30"]
    g6 = vlan + m.HSRP_V6_GROUP_OFFSET
    c.a(" standby version 2",
        f" standby {vlan} ip {host(site, vlan, 1)}", *hsrp(vlan),
        f" standby {g6} ipv6 autoconfig",
        f" standby {g6} ipv6 {v6host(site, vlan, 1)}/64", *hsrp(g6),
        " no shutdown",
        "!")


def _clean(c: Cfg):
    # remove the '!'-placeholder lines that were emitted for conditional blocks
    out = []
    for ln in c.lines:
        if ln == "!" and out and out[-1] == "!":
            continue
        out.append(ln)
    c.lines = out


