def gen_dcsrv(name):
    site = "HQ"
    c = Cfg()
    header(c, name, "Centralised DHCP / DHCPv6 / DNS / NTP for all three sites")
    baseline(c, name, "router", ntp=False)
    c.a("ntp master 3", "ip domain-lookup", "!",
        "interface GigabitEthernet0/0", " description DC services VLAN 100 -> HCMC-ACC-SW02 Gi0/2",
        f" ip address {m.DHCP_SERVER} {mask(site, 100)}",
        f" ipv6 address {m.DHCP_SERVER6}/64",
        " ipv6 dhcp server DHCP6-STATELESS", " no shutdown", "!",
        "interface GigabitEthernet0/1", " shutdown", "interface GigabitEthernet0/2", " shutdown",
        "interface GigabitEthernet0/3", " shutdown", "!",
        f"ip route 0.0.0.0 0.0.0.0 {host(site, 100, 1)}",
        f"ipv6 route ::/0 {v6host(site, 100, 1)}", "!",
        "ipv6 dhcp pool DHCP6-STATELESS", f" dns-server {m.DHCP_SERVER6}", f" domain-name {m.DOMAIN}", "!",
        "! ---- DHCPv4 pools: one per VLAN per site (clients reach us through DHCP relay) ----")
    for s_ in SITES:
        for v in dhcp_vlans(s_):
            n = ipa_net(SITE_VLANS[s_][v])
            c.a(f"ip dhcp excluded-address {n.network_address + 1} {n.network_address + min(m.DHCP_EXCLUDED, n.num_addresses - 3)}")
    lease = {40: "1", 50: "0 4", 60: "7", 61: "7", 62: "7"}
    for s_ in SITES:
        for v in dhcp_vlans(s_):
            n = ipa_net(SITE_VLANS[s_][v])
            dns = "8.8.8.8 1.1.1.1" if v == 50 else m.DHCP_SERVER
            c.a(f"ip dhcp pool P-{SITES[s_]['code']}-V{v}-{VLAN_NAMES[v]}",
                f" network {n.network_address} {n.netmask}",
                f" default-router {host(s_, v, 1)}",
                f" dns-server {dns}")
            if v != 50:   # guests learn nothing about the internal domain / NTP
                c.a(f" domain-name {m.DOMAIN}", f" option 42 ip {m.NTP_SERVER}")
            c.a(f" lease {lease.get(v, '0 8')}")
    c.a("!", "! ---- DNS (authoritative for tvi.local, forwarder for everything else) ----",
        "ip dns server", "ip name-server 8.8.8.8",
        f"ip host dc-srv01.{m.DOMAIN} {m.DHCP_SERVER}",
        f"ip host intranet.{m.DOMAIN} {m.IOT_PLATFORM}",
        f"ip host iot-platform.{m.DOMAIN} {m.IOT_PLATFORM}",
        f"ip host auto-host.{m.DOMAIN} {m.SYSLOG_HOST}", "!")
    post_load(c, name)
    _clean(c)
    return c.text()


