def _lite_baseline(c, name):
    c.a(f"hostname {name}", "no ip domain-lookup", "service timestamps log datetime msec localtime",
        "ip cef", "ipv6 unicast-routing", "!",
        f"username {m.ADMIN_USER} privilege 15 secret 5 {m.SECRET5}",
        f"enable secret 5 {m.SECRET5}", "line con 0", " exec-timeout 0 0", " logging synchronous", "!")


def gen_isp(name):
    c = Cfg()
    header(c, name, "Service-provider simulation (not part of TVI's network)")
    _lite_baseline(c, name)
    asn = m.AS_ISP_A if name == m.ISPA else m.AS_ISP_B
    agg = m.ISP_AGG[name]
    net_link = m.ISP_NET_LINK[name]
    c.a("interface Loopback0", f" ip address {m.ISP_LO[name]} 255.255.255.255", "!")
    custs = []
    for edge, w in WAN.items():
        if w["isp"] != name:
            continue
        c.a(f"interface GigabitEthernet{w['isp_if'][2:]}", f" description customer {edge}",
            f" ip address {w['isp_ip']} {w['mask']}", " no shutdown", "!")
        custs.append((edge, w))
    c.a(f"interface GigabitEthernet{net_link['isp_if'][2:]}", f" description transit -> {m.NET}",
        f" ip address {net_link['isp_ip']} {net_link['mask']}", " no shutdown", "!",
        f"ip route {agg.split('/')[0]} 255.255.255.0 Null0",
        "ip prefix-list PL-DEFAULT-ONLY seq 5 permit 0.0.0.0/0",
        "ip prefix-list PL-DENY-ALL seq 5 deny 0.0.0.0/0 le 32",
        f"router bgp {asn}", f" bgp router-id {m.ISP_LO[name]}", " bgp log-neighbor-changes",
        " no bgp default ipv4-unicast")
    for edge, w in custs:
        c.a(f" neighbor {w['ip']} remote-as {m.AS_TVI}", f" neighbor {w['ip']} description customer {edge}",
            f" neighbor {w['ip']} password {m.BGP_KEY}", f" neighbor {w['ip']} timers 3 9")
    c.a(f" neighbor {net_link['net_ip']} remote-as {m.AS_NET}",
        f" neighbor {net_link['net_ip']} description transit {m.NET}",
        " address-family ipv4", f"  network {agg.split('/')[0]} mask 255.255.255.0")
    for edge, w in custs:
        c.a(f"  neighbor {w['ip']} activate", f"  neighbor {w['ip']} default-originate",
            f"  neighbor {w['ip']} prefix-list PL-DENY-ALL in",
            f"  neighbor {w['ip']} prefix-list PL-DEFAULT-ONLY out")
    c.a(f"  neighbor {net_link['net_ip']} activate", " exit-address-family", "!", "end")
    return c.text()


def gen_internet():
    c = Cfg()
    header(c, m.NET, "Simulated Internet: SaaS/DNS target 8.8.8.8 reachable through both ISPs")
    _lite_baseline(c, m.NET)
    c.a("interface Loopback0", f" ip address {m.ISP_LO[m.NET]} 255.255.255.255", "!",
        "interface Loopback1", " description SaaS / public DNS stand-in", f" ip address {m.SAAS_IP} 255.255.255.255", "!")
    for isp, nl in m.ISP_NET_LINK.items():
        c.a(f"interface GigabitEthernet{nl['net_if'][2:]}", f" description -> {isp}",
            f" ip address {nl['net_ip']} {nl['mask']}", " no shutdown", "!")
    c.a(f"router bgp {m.AS_NET}", f" bgp router-id {m.ISP_LO[m.NET]}", " no bgp default ipv4-unicast")
    for isp, nl in m.ISP_NET_LINK.items():
        asn = m.AS_ISP_A if isp == m.ISPA else m.AS_ISP_B
        c.a(f" neighbor {nl['isp_ip']} remote-as {asn}")
    c.a(" address-family ipv4", f"  network {m.SAAS_IP} mask 255.255.255.255")
    for isp, nl in m.ISP_NET_LINK.items():
        c.a(f"  neighbor {nl['isp_ip']} activate")
    c.a(" exit-address-family", "!", "end")
    return c.text()


# --------------------------------------------------------------------------------------
GENERATORS = {"core": gen_core, "access": gen_access, "edge": gen_edge, "dcsrv": gen_dcsrv}


def render_all():
    out = {}
    for name, d in DEVICES.items():
        if d["role"] in GENERATORS:
            txt = GENERATORS[d["role"]](name)
            sub = SITES[d["site"]]["dirname"]
        elif d["role"] == "isp":
            txt, sub = gen_isp(name), "ISP_Configs"
        else:
            txt, sub = gen_internet(), "ISP_Configs"
        out[f"Configurations/{sub}/{name}.cfg"] = txt
    return out


def main():
    files = render_all()
    for rel, txt in files.items():
        p = ROOT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(txt)
    print(f"wrote {len(files)} startup-configs under {ROOT / 'Configurations'}")


if __name__ == "__main__":
    main()
