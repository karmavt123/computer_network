def gen_access(name):
    d = DEVICES[name]
    site = d["site"]
    c = Cfg()
    header(c, name, "Access switch - RSTP, DHCP snooping, DAI, port security, BPDU guard")
    baseline(c, name, "switch")
    c.a("no ip routing", "!")
    vl = vlans_of(site)
    vl = [v for v in vl if v != 90]
    if site != "HQ" and 100 in vl:
        vl.remove(100)
    vlan_db(c, vl)
    snoop = [v for v in dhcp_vlans(site) if v != 100]
    c.a("! ---- Spanning tree ----",
        "spanning-tree mode rapid-pvst",
        "spanning-tree extend system-id",
        "spanning-tree portfast default",
        "spanning-tree portfast bpduguard default",
        "errdisable recovery cause bpduguard psecure-violation",
        "errdisable recovery interval 300",
        "!",
        "! ---- Layer-2 security: DHCP snooping + Dynamic ARP Inspection on user VLANs ----",
        "ip dhcp snooping",
        "ip dhcp snooping vlan " + ",".join(map(str, snoop)),
        "no ip dhcp snooping information option",
        "ip arp inspection vlan " + ",".join(map(str, snoop)),
        "ip arp inspection validate src-mac dst-mac ip",
        "!")
    mg = host(site, 99, 11 if name != m.ACC2 else 12)
    c.a("interface Vlan99",
        " description Management",
        f" ip address {mg} {mask(site, 99)}",
        " no shutdown", "!",
        f"ip default-gateway {host(site, 99, 1)}", "!")
    trunk = ",".join(map(str, sorted(vl)))
    used = set()
    for (da, ia, db, ib, kind, note) in LINKS:
        for (me, mi, peer, pi) in ((da, ia, db, ib), (db, ib, da, ia)):
            if me != name:
                continue
            used.add(mi)
            if kind == "trunk":
                c.a(f"interface GigabitEthernet{mi[2:]}",
                    f" description UPLINK -> {peer} {pi}",
                    " switchport trunk encapsulation dot1q", " switchport mode trunk",
                    " switchport trunk native vlan 998",
                    f" switchport trunk allowed vlan {trunk}",
                    " switchport nonegotiate",
                    " ip dhcp snooping trust", " ip arp inspection trust",
                    " no shutdown", "!")
            elif kind == "access":
                vlan = int(note.split()[-1])
                infra = vlan in (99, 100)
                c.a(f"interface GigabitEthernet{mi[2:]}",
                    f" description {peer} (VLAN {vlan} {VLAN_NAMES[vlan]})",
                    " switchport mode access", f" switchport access vlan {vlan}",
                    " switchport nonegotiate",
                    " switchport port-security",
                    f" switchport port-security maximum {1 if infra else 2}",
                    " switchport port-security violation restrict",
                    " switchport port-security mac-address sticky",
                    " spanning-tree portfast", " spanning-tree bpduguard enable",
                    " storm-control broadcast level 5.00",
                    *([] if infra else [" ip dhcp snooping limit rate 15", " ip arp inspection limit rate 50"]),
                    " no shutdown", "!")
    for p in ALL_PORTS:
        if p not in used:
            c.a(f"interface GigabitEthernet{p[2:]}", " description UNUSED - blackhole VLAN, shut",
                " switchport mode access", " switchport access vlan 999", " shutdown", "!")
    post_load(c, name)
    _clean(c)
    return c.text()


