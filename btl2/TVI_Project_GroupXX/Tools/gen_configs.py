ROOT = Path(__file__).resolve().parent.parent


class Cfg:
    def __init__(self):
        self.lines: list[str] = []

    def a(self, *lines):
        for ln in lines:
            self.lines.extend(ln.split("\n") if isinstance(ln, str) else ln)
        return self

    def bang(self):
        if self.lines and self.lines[-1] != "!":
            self.lines.append("!")
        return self

    def text(self):
        return "\n".join(self.lines).rstrip() + "\n"


